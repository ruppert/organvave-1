"""Writes firmware/src/eng_eq_tables.h: the organ's equaliser, three biquads (R. Bristow-Johnson's Audio EQ Cookbook, a0 = 1,
Q14, at 44100 Hz): a low shelf at 120 Hz, a peak with a frequency and a high shelf at 4 kHz, each from -12 to +12 dB in 1 dB steps.

   EQ_LS[25][5], EQ_HS[25][5]   {b0, b1, b2, a1, a2} for the gain index g = dB + 12
   EQ_PK[12][25][5]             the peak: frequency index (EQ_FREQ_HZ, ascending), then g

   python3 tools/gen_eq_tables.py"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "firmware", "src", "eng_eq_tables.h")
FS = 44100.0
LOW_HZ, HIGH_HZ = 120.0, 4000.0
FREQS = [160, 225, 320, 450, 640, 900, 1280, 1800, 2560, 3600, 5100, 7200]
PEAK_Q = 0.8


def norm(b0, b1, b2, a0, a1, a2):
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]


def low_shelf(db):
    A = 10 ** (db / 40.0)
    w = 2 * math.pi * LOW_HZ / FS
    c, al = math.cos(w), math.sin(w) / 2 * math.sqrt(2)          # shelf slope 1
    t = 2 * math.sqrt(A) * al
    return norm(A * ((A + 1) - (A - 1) * c + t), 2 * A * ((A - 1) - (A + 1) * c), A * ((A + 1) - (A - 1) * c - t),
                (A + 1) + (A - 1) * c + t, -2 * ((A - 1) + (A + 1) * c), (A + 1) + (A - 1) * c - t)


def high_shelf(db):
    A = 10 ** (db / 40.0)
    w = 2 * math.pi * HIGH_HZ / FS
    c, al = math.cos(w), math.sin(w) / 2 * math.sqrt(2)
    t = 2 * math.sqrt(A) * al
    return norm(A * ((A + 1) + (A - 1) * c + t), -2 * A * ((A - 1) + (A + 1) * c), A * ((A + 1) + (A - 1) * c - t),
                (A + 1) - (A - 1) * c + t, 2 * ((A - 1) - (A + 1) * c), (A + 1) - (A - 1) * c - t)


def peak(hz, db):
    A = 10 ** (db / 40.0)
    w = 2 * math.pi * hz / FS
    c, al = math.cos(w), math.sin(w) / (2 * PEAK_Q)
    return norm(1 + al * A, -2 * c, 1 - al * A, 1 + al / A, -2 * c, 1 - al / A)


def q14(v):
    return int(round(v * 16384))


def row(c):
    return "{" + ", ".join("%d" % q14(v) for v in c) + "}"


def main():
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/gen_eq_tables.py: the organ's equaliser (eng_eq.c). Do not edit. */",
         "static const int32_t EQ_LS[25][5] = {"]
    big = 0
    for g in range(25):
        c = low_shelf(g - 12)
        big = max(big, max(abs(v) for v in c))
        L.append("    %s,%s" % (row(c), "  /* %+d dB */" % (g - 12)))
    L += ["};", "static const int32_t EQ_HS[25][5] = {"]
    for g in range(25):
        c = high_shelf(g - 12)
        big = max(big, max(abs(v) for v in c))
        L.append("    %s,%s" % (row(c), "  /* %+d dB */" % (g - 12)))
    L += ["};", "static const uint16_t EQ_FREQ_HZ[12] = {%s};" % ", ".join(str(f) for f in FREQS),
          "static const int32_t EQ_PK[12][25][5] = {"]
    for f in FREQS:
        L.append("    {  /* %d Hz */" % f)
        for g in range(25):
            c = peak(f, g - 12)
            big = max(big, max(abs(v) for v in c))
            L.append("        %s," % row(c))
        L.append("    },")
    L.append("};")
    open(SRC, "w").write("\n".join(L) + "\n")
    print("wrote %s (largest coefficient %.3f)" % (SRC, big))


if __name__ == "__main__":
    main()
