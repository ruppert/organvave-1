"""The organ's factory presets: tools/organ_bank.py (physical units) -> firmware/src/eng_organ_presets.h.

    python3 tools/gen_organ_presets.py

Writes ORG_NFACTORY, ORG_FACTORY[n][ORG_PSIZE] (the organ patch, eng_organ.c OP_*) and ORG_PRESETS (the engine's
preset_t list: the name, the reverb send). The level (P_LEVEL: 112 = 0 dB, 0.5 dB a step) makes every preset's C major
chord (keys 24 28 31: C4 E4 G4 at 8') as loud (rms) as JAZZ's at 0 dB: computed from setBfree's contributions
(tools/setbfree_ref/tonegen_dump.txt), the wheels taken as independent sines, with the key compression of 3 keys.
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from organ_bank import BANK  # noqa: E402

OUT = os.path.join(HERE, "..", "firmware", "src", "eng_organ_presets.h")
DUMP = os.path.join(HERE, "setbfree_ref", "tonegen_dump.txt")
PSIZE = 64
OP_UB, OP_LB, OP_PB, OP_TEMP, OP_XTALK = 0, 9, 18, 27, 28
OP_ROT, OP_ROT_MODEL, OP_ROT_SPEED, OP_ROT_HORN, OP_ROT_MIC, OP_ROT_BAL = 34, 35, 36, 37, 38, 39
OP_DRV, OP_DRV_GAIN = 40, 41
OP_DRV_TYPE, OP_DRV_TONE, OP_DRV_OUT = 48, 49, 50     # 0.9.2: the type, the tone and the output (9 steps, "zero is the default")
TEMPS = {"gear60": 0, "gear50": 1, "equal": 2}


def effects(p, fx):
    """The rotary and the drive bytes (0.3.0). Without them the neutral values are written (horn level even, gain 0 dB),
    so that switching an effect on in the panel starts from a sensible place."""
    p[OP_ROT_BAL] = 4
    p[OP_DRV_GAIN] = 6
    if "rot" in fx:
        model, speed, horn, width, hdb = fx["rot"]
        assert model in ("classic", "light") and speed in ("stop", "slow", "fast") and horn in ("normal", "sharp")
        assert width in (0, 30, 60, 90, 120, 150, 180) and -6 <= hdb <= 6
        p[OP_ROT] = 1
        p[OP_ROT_MODEL] = 0 if model == "classic" else 1
        p[OP_ROT_SPEED] = ("stop", "slow", "fast").index(speed)
        p[OP_ROT_HORN] = 0 if horn == "normal" else 1
        p[OP_ROT_MIC] = (180 - width) // 30
        p[OP_ROT_BAL] = 4 + int(round(hdb / 1.5))
    if "drv" in fx:
        gdb, typ, tone, odb = fx["drv"]
        assert -12 <= gdb <= 12 and typ in ("distortion", "tube") and -4 <= tone <= 4 and -8 <= odb <= 8 and odb % 2 == 0
        p[OP_DRV] = 1
        p[OP_DRV_GAIN] = 6 + int(round(gdb / 2))
        p[OP_DRV_TYPE] = 0 if typ == "distortion" else 1
        p[OP_DRV_TONE] = (tone + 4 + 5) % 9              # the byte for the index (the default 4 is byte 0)
        p[OP_DRV_OUT] = (odb // 2 + 4 + 5) % 9


def bars(s):
    d = s.replace(" ", "")
    assert len(d) == 9 and all(c in "012345678" for c in d), s
    return [int(c) for c in d]


def load():
    contrib = {True: {}, False: {}}
    for line in open(DUMP):
        t = line.split()
        if t and t[0] in ("contrib", "contribnx"):
            contrib[t[0] == "contrib"].setdefault(int(t[1]), []).append((int(t[2]), int(t[3]), float(t[4])))
    return contrib


def chord_rms(contrib, ub, xt, keys=(24, 28, 31)):
    g = {}
    for k in keys:
        for w, b, v in contrib[xt][k]:
            if b < 9:
                g[w] = g.get(w, 0.0) + v * ub[b] / 8.0
    return math.sqrt(sum(x * x for x in g.values()) / 2.0)


def main():
    contrib = load()
    ref = chord_rms(contrib, bars("88 8000 000"), True)
    L = ["/* SPDX-License-Identifier: GPL-3.0-only",
         " * Generated by tools/gen_organ_presets.py from tools/organ_bank.py. Do not edit. */",
         "#ifndef ENG_ORGAN_PRESETS_H", "#define ENG_ORGAN_PRESETS_H", "",
         "#define ORG_NFACTORY %du" % len(BANK), "",
         "/* the organ patch of each factory preset (eng_organ.c OP_*) */",
         "static const uint8_t ORG_FACTORY[ORG_NFACTORY][ORG_PSIZE] = {"]
    levels = []
    for name, up, lo, pe, tun, xt, rev, *fx in BANK:
        fx = fx[0] if fx else {}
        assert len(name) <= 12 and name == name.upper(), name
        p = [0] * PSIZE
        p[OP_UB:OP_UB + 9] = bars(up)
        p[OP_LB:OP_LB + 9] = bars(lo)
        p[OP_PB:OP_PB + 9] = bars(pe)
        p[OP_TEMP] = TEMPS[tun]
        p[OP_XTALK] = 1 if xt else 0
        effects(p, fx)
        db = 20 * math.log10(ref / chord_rms(contrib, bars(up), xt))
        lv = max(1, min(127, 112 + int(round(2 * db))))
        levels.append((name, db, lv))
        L.append("    {%s},   /* %s */" % (", ".join(str(x) for x in p), name))
    L.append("};")
    L.append("")
    L.append("/* level (P_LEVEL, 112 = 0 dB) of each factory preset: the C major chord as loud as JAZZ's */")
    L.append("static const uint8_t ORG_LEVEL[ORG_NFACTORY] = {%s};" % ", ".join(str(lv) for _, _, lv in levels))
    L.append("")
    L.append("/* the engine's presets: the name and the reverb send (FX(dist, chorus, delay, reverb)) */")
    L.append("static const preset_t ORG_PRESETS[ORG_NFACTORY] = {")
    for (name, up, lo, pe, tun, xt, rev, *_) in BANK:
        L.append('    {"%s", {0, 0, 0, 0, 0, 0, 0, 0}, {0, 64, 127, 10}, 0, 0, FX(0, 0, 0, %d)},' % (name, rev))
    L.append("};")
    L.append("")
    L.append("#endif")
    open(OUT, "w").write("\n".join(L) + "\n")
    for name, db, lv in levels:
        print("%-12s %+6.2f dB  level %d" % (name, db, lv))
    print("wrote", os.path.relpath(OUT))


if __name__ == "__main__":
    main()
