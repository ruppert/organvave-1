# The power-on picture (docs/organvave-splash.png, the owner's) -> firmware/src/organvave_splash.h: 240 x 240, an adaptive
# 256-colour palette (RGB565) and one byte a pixel.   python3 tools/gen_splash.py   (the header is checked in)
import pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
im = Image.open(root / "docs" / "organvave-splash.png").convert("RGB").resize((240, 240), Image.LANCZOS)
q = im.quantize(256, method=Image.MEDIANCUT, dither=Image.FLOYDSTEINBERG)
pal = q.getpalette()[:768]
pal565 = [((pal[3 * i] & 0xF8) << 8) | ((pal[3 * i + 1] & 0xFC) << 3) | (pal[3 * i + 2] >> 3) for i in range(256)]
px = bytes(q.tobytes())
out = ["/* SPDX-License-Identifier: GPL-3.0-only",
       " * Generated by tools/gen_splash.py from docs/organvave-splash.png (do not edit by hand). */",
       "static const uint16_t ORGANVAVE_SPLASH_PAL[256] = {"]
out += ["    " + ", ".join("0x%04X" % c for c in pal565[i:i + 12]) + "," for i in range(0, 256, 12)]
out += ["};", "static const uint8_t ORGANVAVE_SPLASH[240 * 240] = {"]
out += ["    " + ",".join(str(b) for b in px[i:i + 40]) + "," for i in range(0, len(px), 40)]
out += ["};"]
(root / "firmware" / "src" / "organvave_splash.h").write_text("\n".join(out) + "\n")
print("wrote organvave_splash.h", len(px), "pixels")
