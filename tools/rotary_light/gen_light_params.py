"""Writes firmware/src/eng_rotary_light_params.h (the rotary LIGHT's constants) from tools/rotary_light/fit.json, the
fit of the float model (light_fit.c) to CLASSIC's sidebands (fit.py). Fixed point: delays in Q16 samples, geometry in
Q10 samples squared, gains and filters in Q14, angles as 32-bit phases (2^32 = one turn)."""
import json, math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
d = json.load(open(os.path.join(HERE, "fit.json")))
FS = 44100.0

def ph(x): return int(round((x % 1.0) * 4294967296.0)) & 0xFFFFFFFF
def q(x, bits): return int(round(x * (1 << bits)))

def lpf(fc, qq=0.70710678):
    w0 = 2 * math.pi * fc / FS; c = math.cos(w0); al = math.sin(w0) / (2 * qq)
    b0 = (1 - c) / 2; b1 = 1 - c; b2 = b0; a0 = 1 + al; a1 = -2 * c; a2 = 1 - al
    return [b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0]

out = []
out.append("/* SPDX-License-Identifier: GPL-3.0-only\n * Copyright (C) 2026 Guilherme Ruppert (OrganVave-1) */")
out.append("/* GENERATED by tools/rotary_light/gen_light_params.py from tools/rotary_light/fit.json. Do not edit.")
out.append(" * The rotary LIGHT's constants: a distance is sqrt(P + Q cos(2 pi angle)) samples (P, Q in Q10 samples squared),")
out.append(" * a gain a + b cos(2 pi angle) (Q14), the angles 32-bit phases. Horn tap k of mic m: angle = rotor + m PSI + PH[k]")
out.append(" * (its gain at + GPH[k] instead), delay + S[k]; the drum's tap of mic m: rotor + m DPSI (gain at + DGPH). */")
out.append("#define LT_HP %d\n#define LT_HQ %d" % (q(d["HP"], 10), q(d["HQ"], 10)))
out.append("#define LT_DP %d\n#define LT_DQ %d" % (q(d["DP"], 10), q(d["DQ"], 10)))
out.append("#define LT_PSI 0x%08Xu\n#define LT_DPSI 0x%08Xu\n#define LT_DGPH 0x%08Xu" % (ph(d["PSI"]), ph(d["DPSI"]), ph(d["DGPH"])))
out.append("#define LT_DA %d\n#define LT_DB %d" % (q(d["DA"], 14), q(d["DB"], 14)))
out.append("#define LT_HLEV %d                 /* the horn's level, Q14 */\n#define LT_DLEV %d                 /* the drum's */" % (q(d["HL"], 14), q(d["DL"], 14)))
out.append("static const int32_t LT_S[2] = {%d, %d};                       /* the taps' extra delay, Q16 samples */" % (q(d["HS1"], 16), q(d["HS2"], 16)))
out.append("static const uint32_t LT_PH[2] = {0x%08Xu, 0x%08Xu};          /* the taps' delay angle */" % (ph(d["HPH1"]), ph(d["HPH2"])))
out.append("static const uint32_t LT_GPH[2] = {0x%08Xu, 0x%08Xu};         /* the taps' gain angle */" % (ph(d["HGPH1"]), ph(d["HGPH2"])))
out.append("static const int32_t LT_GA[2] = {%d, %d}, LT_GB[2] = {%d, %d};  /* the taps' gain a, b (Q14) */" % (q(d["HA1"], 14), q(d["HA2"], 14), q(d["HB1"], 14), q(d["HB2"], 14)))
x = lpf(d["FC"])
out.append("static const int32_t LT_XO[5] = {%s};      /* the crossover's low-pass, %.0f Hz: b0 b1 b2 a1 a2, Q14 */" % (", ".join(str(q(v, 14)) for v in x), d["FC"]))
out.append("static const int32_t LT_TONE[2][5] = {          /* the horn's tone (a biquad fitted to CLASSIC's horn filters): default, sharp; b0 b1 b2 a1 a2, Q14 */")
for k in ("TONE_DEFAULT", "TONE_SHARP"):
    out.append("    {%s}," % ", ".join(str(q(v, 14)) for v in d[k]))
out.append("};")
open(os.path.join(ROOT, "firmware", "src", "eng_rotary_light_params.h"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
