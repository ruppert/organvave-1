"""Writes firmware/src/eng_rotary_tables.h (the rotary CLASSIC's angle tables, 1024 angles) from
tools/setbfree_ref/whirl_tables.bin, which tools/setbfree_ref/whirl_tables.c writes from setBfree's own whirl.c
(default geometry: horn 19.2 cm, drum 22 cm, mic 42 cm, 44.1 kHz).

   python3 tools/gen_rotary_tables.py            # from the checked-in .bin
   python3 tools/gen_rotary_tables.py FILE.bin   # from another dump

Layout of the .bin (little endian): "WHL1"; 1024 records of int32 horn forward, horn backward, drum forward, drum
backward (Q12 samples), int16 x 5 horn forward FIR, int16 x 5 horn backward FIR (Q15); then int32 x 12 tap phases
(horn 0..5, drum 6..11, in 16384ths of a turn) and float32 x 12 spacings (the same order, samples).
The header: ROT_DISP[4][1024] (int32, Q12), ROT_FIR[2][1024][5] (int16, Q15), ROT_PHASE[12] (int32), ROT_SPACE[12]
(int32, Q12). The firmware interpolates between the 1024 angles (ORGAN.md, the rotary CLASSIC)."""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "firmware", "src", "eng_rotary_tables.h")
NA = 1024


def read(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"WHL1":
        sys.exit(f"{path}: not a whirl table dump (magic {data[:4]!r})")
    body = 4 + NA * (16 + 20)
    if len(data) != body + 96 + 100:
        sys.exit(f"{path}: {len(data)} bytes, expected {body + 96 + 100}")
    disp = [[0] * NA for _ in range(4)]
    fir = [[[0] * 5 for _ in range(NA)] for _ in range(2)]
    off = 4
    for i in range(NA):
        d = struct.unpack_from("<4i", data, off)
        off += 16
        for k in range(4):
            disp[k][i] = d[k]
        c = struct.unpack_from("<10h", data, off)
        off += 20
        fir[0][i] = list(c[0:5])
        fir[1][i] = list(c[5:10])
    phase = list(struct.unpack_from("<12i", data, off))
    off += 48
    space = list(struct.unpack_from("<12f", data, off))
    space_q12 = [round(v * 4096) for v in space]
    off += 48
    bq = list(struct.unpack_from("<25f", data, off))
    return disp, fir, phase, space_q12, bq


def arr(vals, per_line=12):
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "setbfree_ref", "whirl_tables.bin")
    disp, fir, phase, space, bq = read(src)
    out = []
    out.append("/* SPDX-License-Identifier: GPL-3.0-only")
    out.append(" * Copyright (C) 2026 Guilherme Ruppert (OrganVave-1) */")
    out.append("/* GENERATED by tools/gen_rotary_tables.py from tools/setbfree_ref/whirl_tables.bin (setBfree's whirl.c,")
    out.append(" * default geometry). Do not edit. The rotary CLASSIC's angle tables, 1024 angles (one per 16 of 16384):")
    out.append(" * ROT_DISP[0] horn forward, [1] horn backward, [2] drum forward, [3] drum backward (Q12 samples);")
    out.append(" * ROT_FIR[0] / [1] the horn's forward / backward angle FIRs (Q15); ROT_PHASE the tap phases (16384ths:")
    out.append(" * horn 0..5, drum 6..11); ROT_SPACE the reflections' spacings (Q12 samples, the same order); ROT_BQ the biquads (Q24). */")
    out.append("#define ROT_NA 1024")
    out.append("#define ROT_STEP 16                    /* 16384 / ROT_NA */")
    out.append("")
    out.append("static const int32_t ROT_DISP[4][ROT_NA] = {")
    for k in range(4):
        out.append("  {")
        out.append(arr(disp[k]))
        out.append("  },")
    out.append("};")
    out.append("")
    out.append("static const int16_t ROT_FIR[2][ROT_NA][5] = {")
    for k in range(2):
        out.append("  {")
        for i in range(NA):
            out.append("    {" + ", ".join(str(v) for v in fir[k][i]) + "},")
        out.append("  },")
    out.append("};")
    out.append("")
    out.append("static const int32_t ROT_PHASE[12] = {")
    out.append(arr(phase, 6))
    out.append("};")
    out.append("static const int32_t ROT_SPACE[12] = {")
    out.append(arr(space, 6))
    out.append("};")
    # the five filters (setBfree's setIIRFilter: horn A, horn B, the drum's high-shelf, sharp horn A, sharp horn B) in
    # coupled form, Q24. With B = (1, 0) and A = [[s, w], [-w, s]] (poles s +- jw) and C = (c0, c1), D = b0 follow from
    # the biquad in closed form: s = -a1/2, w = sqrt(a2 - a1^2/4), c0 = b1 - b0 a1, c1 = (b0 a2 - c0 s - b2) / w.
    # The engine's direct form I of these biquads rounds at 2^-14: 45 dB (horn B) to 32 dB (drum) of error. Coupled,
    # 73 to 79 dB (eng_rotary.c, rot_cpl). Each set: s, w, c0, c1, d.
    out.append("/* the five filters in coupled form, Q24 (see tools/gen_rotary_tables.py): per set s, w (A = [[s, w], [-w, s]]),")
    out.append(" * c0, c1 (C), d (D = b0). [0] default horn A (low-pass 4500 Hz), [1] default horn B (low-shelf 300 Hz),")
    out.append(" * [2] the drum's high-shelf (811.97 Hz, -38.93 dB), [3] sharp horn A (3900 Hz), [4] sharp horn B (300 Hz, -47.9 dB). */")
    out.append("#define ROT_CPL_NSET 5")
    out.append("static const int32_t ROT_CPL[ROT_CPL_NSET][5] = {")
    for k in range(5):
        a1, a2, b0, b1, b2 = bq[k * 5:k * 5 + 5]
        sg = -a1 / 2.0
        wg = (a2 - a1 * a1 / 4.0) ** 0.5
        c0 = b1 - b0 * a1
        c1 = (b0 * a2 - c0 * sg - b2) / wg
        out.append("  {" + ", ".join(str(round(x * (1 << 24))) for x in (sg, wg, c0, c1, b0)) + "},")
    out.append("};")
    out.append("")
    with open(SRC, "w") as f:
        f.write("\n".join(out))
    print(f"{SRC}: {os.path.getsize(SRC)} bytes")


if __name__ == "__main__":
    main()
